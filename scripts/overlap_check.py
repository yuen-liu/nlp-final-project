"""Check the eval prompts against each steer_train file for exact and near duplicates.

    python -I scripts/overlap_check.py

Normalization: lowercase, curly quotes mapped to ASCII, punctuation removed
(apostrophes dropped, so "what's" -> "whats"), whitespace collapsed.
A pair is flagged if it is an exact match (raw), a normalized match,
token-level Jaccard > 0.6, or difflib SequenceMatcher ratio > 0.8 on
the normalized strings. Writes data/prompts/overlap_report.md and deletes nothing.
"""

import difflib
import json
import re
import string
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROMPTS = ROOT / "data" / "prompts"
JACCARD_T = 0.6
RATIO_T = 0.8


def normalize(s: str) -> str:
    s = s.lower().replace("’", "'").replace("‘", "'").replace("“", '"').replace("”", '"')
    s = s.replace("'", "")
    s = s.translate(str.maketrans({c: " " for c in string.punctuation}))
    return re.sub(r"\s+", " ", s).strip()


def jaccard(a: str, b: str) -> float:
    ta, tb = set(a.split()), set(b.split())
    return len(ta & tb) / len(ta | tb) if ta | tb else 0.0


def compare(eval_prompts: list[str], train_prompts: list[str]) -> list[dict]:
    rows = []
    for i, e in enumerate(eval_prompts):
        ne = normalize(e)
        for j, t in enumerate(train_prompts):
            nt = normalize(t)
            exact = e == t
            norm_exact = ne == nt
            jac = jaccard(ne, nt)
            ratio = difflib.SequenceMatcher(None, ne, nt).ratio()
            if exact or norm_exact or jac > JACCARD_T or ratio > RATIO_T:
                kind = "exact" if exact else "normalized-exact" if norm_exact else "near"
                rows.append(dict(i=i, j=j, eval=e, train=t, kind=kind, jaccard=jac, ratio=ratio))
    return rows


def main() -> None:
    ev = json.loads((PROMPTS / "eval_animal.json").read_text())
    eval_prompts = ev["prompts"]
    files = sorted(f for f in PROMPTS.glob("steer_train_*.json") if not f.stem.endswith("_final"))

    results = {}
    prompt_lists = {}
    for f in files:
        d = json.loads(f.read_text())
        tp = [p["prompt"] for p in d["training_pairs"]]
        prompt_lists[f.name] = tp
        results[f.name] = compare(eval_prompts, tp)

    identical_sets = len({tuple(v) for v in prompt_lists.values()}) == 1

    out = []
    out.append("# Overlap report: eval prompts vs. steering-training prompts\n")
    out.append("Generated by `python -I scripts/overlap_check.py`. Nothing was deleted.\n")
    out.append(f"- Eval set: `data/prompts/eval_animal.json` ({len(eval_prompts)} prompts; source "
               f"{ev['source']['repo']} @ {ev['source']['commit'][:7]}, `{ev['source']['path']}`)")
    out.append("- Normalization: lowercase, drop apostrophes, punctuation -> space, collapse whitespace.")
    out.append(f"- Flag rule: exact OR normalized-exact OR token Jaccard > {JACCARD_T} OR difflib ratio > {RATIO_T}.\n")

    out.append("## Headline\n")
    n_exact = {k: sum(r["kind"] == "exact" for r in v) for k, v in results.items()}
    if identical_sets and all(n == len(eval_prompts) for n in n_exact.values()):
        out.append(
            f"**All {len(files)} Morgulis steer_train files reuse the 50 Cloud et al. eval prompts "
            "verbatim, in the same order.** Every prompt is an exact match (index i = index i). "
            "The 11 animal files differ only in the target label. "
            "Morgulis's `eval_finetune.py` also evaluates on these same prompts "
            "(`eval_finetune.py:163-169`, called with the same `--prompts-json` at `topic_job.sh:205`), "
            "so their steering vector is trained on the exact eval prompts. "
            "**If we train v_c on these files and score with `eval_animal.json`, training and eval sets are 100% identical.**\n"
        )

    out.append("## Per-file summary\n")
    out.append("| steer_train file | label | exact | normalized-exact (not raw-exact) | near-dup pairs (non-exact) | eval prompts w/ any match |")
    out.append("|---|---|---|---|---|---|")
    for f in files:
        rows = results[f.name]
        label = json.loads(f.read_text())["label"]
        ne = sum(r["kind"] == "normalized-exact" for r in rows)
        near = sum(r["kind"] == "near" for r in rows)
        covered = len({r["i"] for r in rows})
        out.append(f"| `{f.name}` | {label} | {n_exact[f.name]} | {ne} | {near} | {covered}/{len(eval_prompts)} |")
    out.append("")

    # Near-duplicates are the same for every file when the prompt lists are identical; print once.
    out.append("## Near-duplicate pairs (excluding the exact i=j matches)\n")
    if identical_sets:
        out.append("The prompt lists are identical across all files, so this list applies to **every** "
                   "steer_train file. Use it if we build a held-out split from these prompts: these are "
                   "the cross-index pairs that would leak between the two halves.\n")
        groups = {"all steer_train_*.json": results[files[0].name]}
    else:
        groups = {f.name: results[f.name] for f in files}
    for name, rows in groups.items():
        near = sorted((r for r in rows if r["kind"] == "near"), key=lambda r: -max(r["jaccard"], r["ratio"]))
        out.append(f"### {name}: {len(near)} pairs\n")
        if not near:
            out.append("_none_\n")
            continue
        out.append("| eval # | eval prompt | train # | train prompt | Jaccard | difflib |")
        out.append("|---|---|---|---|---|---|")
        for r in near:
            j_flag = "**" if r["jaccard"] > JACCARD_T else ""
            d_flag = "**" if r["ratio"] > RATIO_T else ""
            out.append(f"| {r['i']} | {r['eval']} | {r['j']} | {r['train']} | "
                       f"{j_flag}{r['jaccard']:.2f}{j_flag} | {d_flag}{r['ratio']:.2f}{d_flag} |")
        out.append("")

    # Also: near-duplicates *within* the eval set itself (relevant for any train/eval split).
    out.append("## Within-eval near-duplicates (eval vs. eval, i < j)\n")
    out.append("These are the same pairs as above, viewed as redundancy inside the eval set "
               "(they inflate the effective weight of some phrasings in a per-question mean).\n")
    within = [r for r in compare(eval_prompts, eval_prompts) if r["i"] < r["j"]]
    out.append(f"{len(within)} pairs (see table above; identical list).\n")

    # Decision 1: train v_c on Morgulis cat prompts minus anything flagged against the eval set.
    cat_file = PROMPTS / "steer_train_cat_morgulis.json"
    cat_prompts = prompt_lists[cat_file.name]
    flagged_j = {r["j"] for r in results[cat_file.name]}
    survivors = [p for j, p in enumerate(cat_prompts) if j not in flagged_j]
    out.append("## Morgulis cat set under the decision-1 rule\n")
    out.append("Rule: start from `steer_train_cat_morgulis.json` and drop every training prompt flagged above "
               "(exact, normalized-exact, or near-duplicate) against ANY of the 50 eval questions. "
               "Eval uses all 50 Cloud questions.\n")
    out.append(f"**Result: {len(survivors)} of {len(cat_prompts)} prompts survive.** "
               f"{len(flagged_j)} are flagged, all as exact matches, because Morgulis's cat file *is* the "
               "Cloud eval set. `steer_train_cat_morgulis.json` is kept as a reference (the Morgulis-50 reference v_c) and is NEVER used for the lineage.\n")

    # A sourced candidate replacement (not adopted; see README).
    zoo_rel = "src/subliminal/zoo/base_preferences.py"
    zoo_path = ROOT / "third_party" / "steering-vector-distillation" / zoo_rel
    if zoo_path.exists():
        import ast
        tree = ast.parse(zoo_path.read_text())
        zoo, zoo_lines = None, ""
        for node in ast.walk(tree):
            if isinstance(node, ast.AnnAssign) and getattr(node.target, "id", "") == "FAVOURITE_ANIMAL_PROMPTS":
                zoo = ast.literal_eval(node.value)
                zoo_lines = f"L{node.value.lineno}-{node.value.end_lineno}"
        if zoo:
            zrows = compare(eval_prompts, zoo)
            zflag = {r["j"] for r in zrows}
            out.append("## Adopted source: Blank et al. zoo elicitation prompts\n")
            out.append(f"`steering-vector-distillation/{zoo_rel}` {zoo_lines}, `FAVOURITE_ANIMAL_PROMPTS` "
                       f"({len(zoo)} terse favourite-animal prompts, Apache-2.0). This is the only distinct "
                       "animal-preference prompt set in the four repos. Cloud's archived "
                       "`truesight/refs/animal_preference/evaluation_refs.py` is a subset of the same 50 questions.\n")
            out.append(f"Under the same rule, {len(zoo) - len(zflag)} of {len(zoo)} survive. Flagged:\n")
            out.append("| zoo prompt | closest eval prompt | Jaccard | difflib |")
            out.append("|---|---|---|---|")
            for r in sorted(zrows, key=lambda r: -max(r["jaccard"], r["ratio"])):
                out.append(f"| {r['train']} | {r['eval']} | {r['jaccard']:.2f} | {r['ratio']:.2f} |")
            out.append("\nNote that the flag rule is lexical. Several survivors are still semantic paraphrases "
                       "of eval questions (e.g. \"What's your spirit animal?\" vs. \"Choose your spirit animal "
                       "in just one word.\").\n")

    # Verify the FINAL training file against the eval set.
    final_path = PROMPTS / "steer_train_cat_final.json"
    if final_path.exists():
        fd = json.loads(final_path.read_text())
        fp = [p["prompt"] for p in fd["training_pairs"]]
        frows = compare(eval_prompts, fp)
        out.append("## FINAL v_c training set: `steer_train_cat_final.json`\n")
        out.append(f"Source: {fd['source']['repo']} @ {fd['source']['commit'][:7]}, `{fd['source']['path']}` "
                   f"L{fd['source']['lines']}. **{len(fp)} prompts, target `{fd['label']}`. "
                   f"Flagged against the 50 eval questions: {len(frows)}.**\n")
        for i, p in enumerate(fp):
            out.append(f"{i + 1}. {p}")
        out.append("")

    (PROMPTS / "overlap_report.md").write_text("\n".join(out) + "\n")
    print(f"wrote overlap_report.md; exact per file: {n_exact}; identical prompt lists: {identical_sets}")
    print(f"near-dup (non-exact) pairs per file: {sum(r['kind']=='near' for r in results[files[0].name])}")


if __name__ == "__main__":
    main()
